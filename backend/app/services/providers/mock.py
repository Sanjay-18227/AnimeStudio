    def generate_text(
        self,
        prompt: str,
        system_instruction: Optional[str] = None,
        model: Optional[str] = None,
        temperature: float = 0.7,
        max_tokens: int = 2048
    ) -> str:
        messages = [{"role": "user", "content": prompt}]
        return self.chat(messages, system_instruction=system_instruction, model=model)

